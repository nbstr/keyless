//! Masking coverage: every encoding, every split, and the limits.
//!
//! In the reference implementation this project was measured against, the
//! masking and injection paths sat at 0.0% test coverage and 6 of 13 encodings
//! leaked. Every variant here therefore gets a positive test, and — just as
//! important — the shapes that *cannot* be caught get a test that asserts they
//! are not caught. A documented limit is worth more than a comment claiming
//! coverage that does not exist.

mod support;

use keyless::mask::encodings::{ALL, Encoding};
use keyless::mask::{Masker, MaskingWriter};
use keyless::secret::Secret;
use std::io::Write;
use std::process::{Command, Stdio};
use std::sync::Arc;

/// A decoy chosen to exercise every escaping rule at once: mixed case, digits,
/// a space, a quote, the HTML trio, a slash, a plus, and a non-ASCII character.
///
/// It is 31 bytes on purpose. 31 divides by neither 3 nor 5, so base64 and
/// base32 both need padding and the padded and unpadded variants are genuinely
/// different strings — at 30 bytes they collide and half the table silently
/// stops testing anything.
const VALUE: &str = "Decoy-Key_é9 \"q\" &<>/ +42?=#~!";

/// Every encoding of [`VALUE`], written out as a literal.
///
