/// The encoding carrying `label`, or a failure naming what went missing.
fn encoding_named(label: &str) -> Encoding {
    *ALL.iter()
        .find(|encoding| encoding.label() == label)
        .unwrap_or_else(|| panic!("the `{label}` encoding is no longer generated"))
}

fn masker() -> Arc<Masker> {
    let secret = Secret::new(VALUE.to_owned());
    Arc::new(Masker::from_secrets([("DECOY", &secret)]))
}

fn through_stream(masker: &Arc<Masker>, text: &str, split_at: usize) -> String {
    let mut sink: Vec<u8> = Vec::new();
    {
        let mut writer = MaskingWriter::new(Arc::clone(masker), &mut sink);
        let bytes = text.as_bytes();
        let split = split_at.min(bytes.len());
        writer.write_all(&bytes[..split]).expect("write");
        writer.write_all(&bytes[split..]).expect("write");
        writer.finish().expect("finish");
    }
    String::from_utf8_lossy(&sink).into_owned()
}

#[test]
fn the_codecs_agree_with_an_independent_oracle() {
    // The hand-rolled base64, base32, hex, percent-encoding and JSON escaping
    // must produce byte-for-byte what Python's standard library produces.
    // Owning a codec is only cheaper than depending on one if it is checked.
    for (label, expected) in EXPECTED {
        let produced = encoding_named(label).encode(VALUE);
        assert_eq!(
            produced, expected,
            "the `{label}` codec disagrees with the oracle"
        );
    }
}

#[test]
fn every_encoding_in_the_table_is_caught_in_a_stream() {
    let masker = masker();
    for (label, rendered) in EXPECTED {
        let line = format!("log line: {rendered} <- end\n");

        // Whole write.
        let masked = through_stream(&masker, &line, line.len());
        assert!(
            !masked.contains(rendered),
            "{label} leaked on a whole write: {masked}"
        );
        assert!(
            masked.contains("[keyless:DECOY]"),
            "{label} produced no mask token: {masked}"
        );

        // Split in the middle of the encoded value — the case a line-oriented
        // matcher gets wrong.
        let middle = "log line: ".len() + rendered.len() / 2;
        let masked = through_stream(&masker, &line, middle);
        assert!(
            !masked.contains(rendered),
            "{label} leaked when split mid-value"
        );
    }
}

#[test]
fn every_encoding_in_the_table_is_caught_at_every_split_point() {
    let masker = masker();
    for (label, rendered) in EXPECTED {
        let line = format!("a{rendered}b");
        for split in 0..=line.len() {
            let masked = through_stream(&masker, &line, split);
            assert!(
                !masked.contains(rendered),
                "{label} leaked when split at byte {split}"
            );
            // An ABSENCE on its own is not a result. This test used to assert
            // only the line above, and a masker that emitted nothing at all
            // satisfied it: the empty string contains no secret. Measured by
            // making `Masker::scan` return an empty buffer — a masker that
            // deletes the whole stream — after which this test stayed green
            // across all twenty encodings and every split point.
            //
            // So the output is pinned exactly. The bracketing `a` and `b` are
            // what make it exact rather than a second `contains`: they prove
            // the bytes around the match survived and that the replacement
            // landed in their place, not merely somewhere.
            assert_eq!(
                masked, "a[keyless:DECOY]b",
                "{label} at split {split}: the stream is not what it should be"
            );
        }
    }
}

#[test]
fn the_generated_set_and_the_table_describe_the_same_encodings() {
    // Catches both directions of drift: an encoding added to the code with no
    // literal to check it, and a literal left behind after an encoding is gone.
    let generated: Vec<&str> = ALL.iter().map(|encoding| encoding.label()).collect();
    let tabled: Vec<&str> = EXPECTED.iter().map(|(label, _)| *label).collect();
    assert_eq!(generated, tabled);
}

#[test]
fn a_credential_embedded_in_a_url_is_caught() {
    // The URL-embedded shape, one of the four the README's *Why this exists*
    // names. It is the one that needs its own test, because the credential sits
    // between a `:` and an `@` rather than at a word boundary.
    let secret = Secret::new("s3cr3t-decoy-password-9999".to_owned());
    let masker = Arc::new(Masker::from_secrets([("DB_PASSWORD", &secret)]));
    let line = "postgres://app:s3cr3t-decoy-password-9999@db.internal:5432/prod";
    let masked = through_stream(&masker, line, 20);
    assert_eq!(
        masked,
        "postgres://app:[keyless:DB_PASSWORD]@db.internal:5432/prod"
    );
}

#[test]
fn a_bearer_token_in_a_curl_trace_is_caught() {
    let secret = Secret::new("ghp_decoyDECOYdecoy0123456789abcd".to_owned());
    let masker = Arc::new(Masker::from_secrets([("GITHUB_TOKEN", &secret)]));
    let line = "> Authorization: Bearer ghp_decoyDECOYdecoy0123456789abcd\r\n";
    let masked = through_stream(&masker, line, 30);
    assert!(masked.contains("[keyless:GITHUB_TOKEN]"));
    assert!(!masked.contains("ghp_decoy"));
}

